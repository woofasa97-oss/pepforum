'use client';

import Link from 'next/link';
import { useActionState, useState, useTransition } from 'react';

import { FieldError, FormMessage } from '@/components/ui/Bits';
import { SubmitButton } from '@/components/ui/SubmitButton';
import { initialActionState } from '@/lib/action-state';
import { type MfaEnrollment, startMfaEnrollmentAction, verifyMfaAction } from '@/server/actions/auth';
import { deleteAccountAction, updateProfileAction } from '@/server/actions/settings';

type Labels = Record<string, string>;

export function ProfileForm({ labels, defaults }: {
  labels: Labels;
  defaults: { bio: string; coi: string; locale: 'en' | 'fr' };
}) {
  const [state, action] = useActionState(updateProfileAction, initialActionState);
  return (
    <form action={action}>
      <FormMessage ok={state.ok} message={state.message} />
      <div className="field">
        <label htmlFor="s-bio">{labels['settings.bio']}</label>
        <textarea id="s-bio" name="bio" className="input" maxLength={500} defaultValue={defaults.bio} style={{ minHeight: 80 }} />
        <FieldError message={state.fieldErrors?.bio} />
      </div>
      <div className="field">
        <label htmlFor="s-coi">{labels['settings.coi']}</label>
        <input id="s-coi" name="coi" className="input" maxLength={300} defaultValue={defaults.coi} aria-describedby="s-coi-hint" />
        <span id="s-coi-hint" className="hint">{labels['settings.coiHint']}</span>
      </div>
      <div className="row wrap" style={{ gap: 12 }}>
        <div className="field grow">
          <label htmlFor="s-locale">{labels['auth.locale']}</label>
          <select id="s-locale" name="locale" className="input" defaultValue={defaults.locale}>
            <option value="en">English</option>
            <option value="fr">Français</option>
          </select>
        </div>
      </div>
      <SubmitButton>{labels['settings.save']}</SubmitButton>
    </form>
  );
}

export function MfaSetup({ labels }: { labels: Labels }) {
  const [enrollment, setEnrollment] = useState<MfaEnrollment | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [pending, startTransition] = useTransition();
  const [state, verify] = useActionState(verifyMfaAction, initialActionState);

  if (!enrollment) {
    return (
      <>
        {error ? <FormMessage ok={false} message={error} /> : null}
        <button type="button" className="btn" disabled={pending} onClick={() => startTransition(async () => {
          const result = await startMfaEnrollmentAction();
          if ('error' in result) setError(result.error);
          else setEnrollment(result);
        })}>
          {labels['settings.mfaEnroll']}
        </button>
      </>
    );
  }

  return (
    <form action={verify}>
      <FormMessage ok={state.ok} message={state.message} />
      <p className="small mb8">{labels['settings.mfaScan']}</p>
      {/* qr_code is an SVG data URI generated by Supabase Auth (CSP allows data: images). */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img className="qr" src={enrollment.qrCode} alt="" width={200} height={200} />
      <p className="xs faint mt8">
        {(labels['settings.mfaSecret'] ?? '{secret}').split('{secret}').map((part, i) => (
          <span key={i}>{i > 0 ? <code className="secret">{enrollment.secret}</code> : null}{part}</span>
        ))}
      </p>
      <input type="hidden" name="factorId" value={enrollment.factorId} />
      <input type="hidden" name="next" value="/settings" />
      <div className="field mt12">
        <label htmlFor="mfa-code">{labels['auth.mfaCode']}</label>
        <input id="mfa-code" name="code" className="input" inputMode="numeric" autoComplete="one-time-code" pattern="\d{6}" maxLength={6} required style={{ maxWidth: 160 }} />
      </div>
      <SubmitButton>{labels['auth.mfaVerify']}</SubmitButton>
    </form>
  );
}

export function DeleteAccountForm({ labels, hasPassword }: { labels: Labels; hasPassword: boolean }) {
  const [state, action] = useActionState(deleteAccountAction, initialActionState);
  return (
    <form action={action}>
      <FormMessage ok={state.ok} message={state.message} />
      <p className="small muted mb12">{labels['settings.deleteBody']}</p>
      <label className="check mb12">
        <input type="checkbox" name="erase" />
        <span>{labels['settings.deleteErase']}</span>
      </label>
      {hasPassword ? (
        <div className="field">
          <label htmlFor="del-pw">{labels['settings.deleteConfirm']}</label>
          <input id="del-pw" name="password" type="password" className="input" autoComplete="current-password" required aria-invalid={Boolean(state.fieldErrors?.password)} />
          <FieldError message={state.fieldErrors?.password} />
        </div>
      ) : (
        <>
          <p className="small muted mb12">
            {labels['settings.deleteSocial']} <Link className="link" href="/auth/sign-in?next=/settings">{labels['settings.deleteReauthLink']}</Link>
          </p>
          <label className="check mb12">
            <input type="checkbox" name="confirm" required />
            <span>{labels['settings.deleteSocialConfirm']}</span>
          </label>
          <FieldError message={state.fieldErrors?.confirm} />
        </>
      )}
      <SubmitButton className="btn danger">{labels['settings.deleteSubmit']}</SubmitButton>
    </form>
  );
}
