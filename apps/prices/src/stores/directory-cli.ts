// pnpm --filter @pepforum/prices stores:check — re-reads every page an audit quotes (robots.txt honoured,
//   as PepforumsBot, one page a second per site) and records the day each quote was found on its page in
//   seed/store-audits.json. A quote not found is reported and left unverified; under publishable() an
//   unverified finding against a store is never published.
// pnpm --filter @pepforum/prices stores:sql <migration file> — validates the three seed files and writes
//   the migration that loads them (directorySql).
import { readFileSync, writeFileSync } from "node:fs";
import { createFetcher } from "../fetch/http.ts";
import { realSleep } from "../fetch/pacing.ts";
import { missingFragments, pageText } from "../vendors/quote-check.ts";
import { directorySql, validateAudits, validateLabs, validateStores } from "./directory.ts";

const say = (line: string) => process.stdout.write(`${line}\n`);
const read = (file: string): unknown => JSON.parse(readFileSync(`seed/${file}`, "utf8"));
const NOT_HTML = /\.(pdf|png|jpe?g|webp|gif|svg)(\?|#|$)/i;

async function check(): Promise<void> {
  const stores = validateStores(read("stores.json"));
  const audits = validateAudits(read("store-audits.json"), stores);
  const today = new Date().toISOString().slice(0, 10);
  const todo = new Map<string, Array<{ slug: string; criterion: string; quote: string; mark: () => void }>>();
  for (const a of audits) {
    for (const [criterion, c] of Object.entries(a.checks)) {
      if (!c.quote || !c.source_url || c.quote_verified_on || NOT_HTML.test(c.source_url)) continue;
      const list = todo.get(c.source_url) ?? [];
      list.push({ slug: a.slug, criterion, quote: c.quote, mark: () => { c.quote_verified_on = today; } });
      todo.set(c.source_url, list);
    }
  }
  // One queue per site, a few sites at a time.
  const bySite = new Map<string, string[]>();
  for (const url of todo.keys()) {
    const host = new URL(url).host;
    bySite.set(host, [...(bySite.get(host) ?? []), url]);
  }
  const fetchText = createFetcher();
  const counts = { found: 0, missing: 0, unread: 0 };
  const sites = [...bySite.values()];
  const worker = async () => {
    for (let urls = sites.shift(); urls; urls = sites.shift()) {
      for (const url of urls) {
        const r = await fetchText(url);
        const quotes = todo.get(url) ?? [];
        if (r.state !== "hit" || r.body === null) {
          counts.unread += quotes.length;
          say(`not read  ${url} (${r.error ?? `status ${r.status ?? "none"}`})`);
        } else {
          const page = pageText(r.body);
          for (const q of quotes) {
            const gone = missingFragments(page, q.quote);
            if (gone.length === 0) {
              q.mark();
              counts.found++;
            } else {
              counts.missing++;
              say(`MISSING   ${q.slug} ${q.criterion}: ${gone.map((g) => JSON.stringify(g)).join(" | ")}`);
            }
          }
        }
        await realSleep(1000);
      }
    }
  };
  await Promise.all(Array.from({ length: 8 }, worker));
  writeFileSync("seed/store-audits.json", `${JSON.stringify(audits, null, 2)}\n`);
  say(`${counts.found} quotes found on their pages, ${counts.missing} missing, ${counts.unread} on pages not read`);
}

function sql(out: string | undefined): void {
  if (!out || !/supabase\/migrations\/\d{14}_[a-z0-9_]+\.sql$/.test(out)) {
    throw new Error("usage: stores:sql ../../supabase/migrations/<timestamp>_<name>.sql");
  }
  const stores = validateStores(read("stores.json"));
  const labs = validateLabs(read("labs.json"));
  const audits = validateAudits(read("store-audits.json"), stores);
  const header = [
    "-- ============================================================================",
    "-- The Stores directory's data (…035, ADR-0011), generated by",
    "-- `pnpm --filter @pepforum/prices stores:sql` from apps/prices/seed/stores.json,",
    "-- labs.json and store-audits.json. Do not edit: change the files and generate",
    "-- a new migration.",
    `-- ${stores.length} stores, ${labs.length} laboratories, ${audits.length} audits under the Standard ${[...new Set(audits.map((a) => a.standard_version))].join(", ") || "-"}.`,
    "-- ============================================================================",
  ].join("\n");
  writeFileSync(out, directorySql(stores, labs, audits, header));
  say(`wrote ${out}`);
}

async function main(): Promise<void> {
  const [command, arg] = process.argv.slice(2);
  if (command === "check") await check();
  else if (command === "sql") sql(arg);
  else throw new Error("usage: directory-cli.ts check | sql <migration file>");
}

main().catch((e: unknown) => {
  process.stderr.write(`${e instanceof Error ? e.message : String(e)}\n`);
  process.exitCode = 1;
});
